export const resolveDiseaseKnowledge = (item = {}) => {
  if (item.disease_id && DISEASE_KNOWLEDGE[item.disease_id]) {
    return DISEASE_KNOWLEDGE[item.disease_id];
  }

  const name = item.name || '';
  return Object.values(DISEASE_KNOWLEDGE).find(
    (entry) =>
      entry.crop === item.target_crop &&
      entry.aliases.some((alias) => name.includes(alias))
  );
};
